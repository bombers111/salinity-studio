const assert=require('node:assert/strict');
const {load,get,set,snapshot,INPUTS}=require('./engine.cjs');
(async()=>{
 const books=await load();
 const base=snapshot(books);
 assert.equal(base.scenario.threshold,8);
 assert.equal(base.scenario.plantingYear,'Year 2');
 assert.ok(Math.abs(base.scenario.years[0].ece-7.657021424569897)<1e-6);
 assert.ok(Math.abs(base.balance.irrigation-431.1185628742515)<1e-6);
 assert.equal(base.diagnosis.classification,'Insufficient data');
 for(const [key,value] of Object.entries({ece:9,ecw:2,sar:10,waterTable:2.5}))
  for(const [book,[sheet,cell]] of Object.entries(INPUTS[key]))set(books,book,sheet,cell,value);
 const sample=snapshot(books);
 assert.equal(sample.diagnosis.classification,"Saline Soil ('White Alkali')");
 assert.equal(sample.diagnosis.salinity,'Strongly saline');
 assert.equal(sample.diagnosis.completeness,'BASELINE COMPLETE');
 assert.equal(sample.scenario.plantingYear,'Year 2');
 assert.ok(sample.balance.irrigation<base.balance.irrigation);
 set(books,'diagnosis','Section A - Field Checklist','F8',16);
 assert.equal(snapshot(books).diagnosis.classification,'Saline-Sodic Soil');
 set(books,'diagnosis','Section A - Field Checklist','E8','< 13.0 (mmol/L)^0.5');
 assert.equal(snapshot(books).diagnosis.classification,"Saline Soil ('White Alkali')");
 let leaching=snapshot(books).diagnosis.measures.find(m=>m.name==='Forced Leaching Regime');
 assert.match(leaching.status,/RECOMMENDED/);
 assert.equal(snapshot(books).diagnosis.selected.length,0);
 set(books,'diagnosis','Section C - Measure Selection','P10','Selected');
 assert.equal(snapshot(books).diagnosis.selected[0].name,'Forced Leaching Regime');
 set(books,'diagnosis','Dashboard','Q5',12);
 assert.equal(snapshot(books).diagnosis.classification,'Normal Soil');
 set(books,'diagnosis','Dashboard','K2','RESET (blank all results)');
 assert.equal(snapshot(books).diagnosis.classification,'Insufficient data');
 assert.equal(snapshot(books).diagnosis.selected.length,0);
 set(books,'diagnosis','Dashboard','K2','LIVE (normal use)');
 assert.equal(snapshot(books).diagnosis.classification,'Normal Soil');
 const before=get(books,'scenario','W&S Balance Model','F5');
 set(books,'scenario','Crop Database','C9',10);
 assert.equal(get(books,'scenario','W&S Balance Model','F5'),10);
 assert.notEqual(before,10);
 assert.equal(get(books,'scenario','Strategy & Crop Advisor','H32'),428);
 assert.equal(get(books,'scenario','Strategy & Crop Advisor','K32'),get(books,'scenario','Strategy & Crop Advisor','J32'));
 console.log('Workbook baseline, dropdown, thresholds, reset, crop data, measure and formula checks passed.');
})().catch(err=>{console.error(err);process.exitCode=1});
